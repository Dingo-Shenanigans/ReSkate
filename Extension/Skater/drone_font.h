// Rows for a character (lower case is shown as capitals); blank for anything unknown.
inline std::array<std::uint8_t, 7> glyph(char c) {
    if (c >= 'a' && c <= 'z') c = static_cast<char>(c - 'a' + 'A');
    for (const auto& g : glyphs) if (g.ch == c) return g.rows;
    return {};
}

