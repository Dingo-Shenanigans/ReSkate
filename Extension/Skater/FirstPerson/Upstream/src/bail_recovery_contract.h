template<class Read> bool verified(Read read,std::uintptr_t base) {
    const auto matches=[&](std::uintptr_t site,const auto& expected) {
        auto actual=expected;return read(base+site,actual.data(),actual.size()) && actual==expected;
    };
    std::uintptr_t update{};
    const auto ground=player_state_contract::normal_foot_states[0];
    return matches(selection_site,selection_prefix) && matches(ground_input_site,ground_input_prefix) &&
        matches(ground_source_site,ground_source_prefix) &&
        read(base+ground.vtable+0x18,&update,sizeof(update)) && update==base+ground.update;
}
inline bool controllable(bool ground,std::uint32_t flags,bool override_motion,bool mounting,bool wipeout) {
    return ground && (flags&normal_control_mask)==normal_control_mask &&
        !(flags&(animation_override_mask|trajectory_request_mask)) && !override_motion && !mounting && !wipeout;
}
