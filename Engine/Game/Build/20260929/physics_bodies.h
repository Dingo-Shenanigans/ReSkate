// Supported SHA-256 fbce74d5e28ef525dbba2cb4adbebc13405bdbd88f31bc940bca45e4ae88b8f9.
// The client physics world's bodies, as the park editor's surface probe and the game's ghosting
// of placed objects use them (read 2026-10-21). A body is a handle {world, index | generation << 32}
// (park_editor_surface.h's SurfaceBody); the world's store is at world + 0x28. In the store:
//   +0x1008  u32 per body: its owner's index. +0x8b0: a bit per owner, clear for an ECS entity;
//            +0x8b8: a u64 per owner, the entity id for an ECS owner (body_entity, 0x3d09a20).
//   +0xf68   a bit per body: a ghost, which skaters go through (the Build Kit's walk-through
//            objects, 0x708de0 -> 0x25d3610 for each body of the object).
// ghost_body(const body*) sets a body's ghost bit and tells the world when it changed;
// solid_body(const body*) clears it (0x708be0 -> 0x25d3170). The game's ghosting also sets the
// object's main body's bit at +0x9f8 (main_ghost 0x25d3360, which tells the world too) and its
// solid side clears it (main_solid 0x25d2e90). Client thread.
inline constexpr std::uintptr_t store_offset = 0x28;
inline constexpr std::uintptr_t body_owner_offset = 0x1008, owner_kind_offset = 0x8b0, owner_value_offset = 0x8b8;
inline constexpr std::uintptr_t ghost_body = 0x25d3610, solid_body = 0x25d3170, main_ghost = 0x25d3360, main_solid = 0x25d2e90;
