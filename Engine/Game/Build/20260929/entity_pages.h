// EntityBus TransformSpace and property-space snapshots have 128 page pointers.
// Slot 131072 formerly indexed pointer 128, overwriting snapshot bookkeeping.
// Enlarge the leaf pages without changing owners, snapshots, IDs or their ABI.
// Four times the game's 131,072 slots (it was eight until 2026-10-10): the largest map load
// seen needed 150,152, and every page set the game keeps is this many times its own size,
// whether a map uses it or not.
inline constexpr std::size_t page_count = 128;
inline constexpr unsigned page_shift = 12;
inline constexpr std::size_t page_entries = std::size_t{1} << page_shift;
inline constexpr std::size_t page_bytes = page_entries * sizeof(std::uint64_t);
inline constexpr std::size_t capacity = page_count * page_entries;
// The native render-instance pool keeps 512 page pointers and stable direct
// object addresses. Grow its 464-byte-record pages without changing that ABI.
inline constexpr unsigned render_instance_page_shift = 11;
inline constexpr std::size_t render_instance_page_bytes = (std::size_t{1} << render_instance_page_shift) * 0x1d0;
// (Left at eight times the game's: its pages are its own, by its own shift.)
static_assert((512u << render_instance_page_shift) >= capacity);
static_assert(render_instance_page_bytes == 0xe8000);
// The cull-ID list and this separate monotonic bounds arena must both fit the
// city. Retail config can override GridSize after Game.cfg has been processed.
// Preserve native allocation/reset ownership and any larger configured value.
inline constexpr std::size_t spatial_arena_min_bytes = 128 * 1024 * 1024;
static_assert(capacity == 524'288 && page_bytes == 32'768);

enum class Kind {
    index_shift, page_bytes, page_entries, spatial_arena_bytes,
    spatial_bucket_layout, spatial_bucket_stride, pending_update_pages,
    render_instance_pages
};
struct Patch {
    std::uintptr_t rva;
    Kind kind;
    std::size_t size;
    std::array<std::uint8_t, 15> expected{};
    std::array<std::uint8_t, 15> replacement{};
};

template<std::size_t N>
consteval Patch patch(std::uintptr_t rva, Kind kind,
                      const char (&before)[N], const char (&after)[N]) {
    static_assert(N % 2 == 1 && N > 1 && N <= 31);
    Patch result{rva, kind, (N - 1) / 2};
    const auto nibble = [](char c) -> unsigned {
        if (c >= '0' && c <= '9') return c - '0';
        if (c >= 'a' && c <= 'f') return c - 'a' + 10;
        throw "Invalid entity-page instruction contract";
    };
    for (std::size_t i = 0; i < result.size; ++i) {
        result.expected[i] = static_cast<std::uint8_t>((nibble(before[i*2]) << 4) | nibble(before[i*2+1]));
        result.replacement[i] = static_cast<std::uint8_t>((nibble(after[i*2]) << 4) | nibble(after[i*2+1]));
    }
    return result;
}

