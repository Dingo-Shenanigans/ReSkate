// The game's UI state flags: one 32-bit word per category (HUD, Menu, Level, Modal, CAS, ... 18 in
// all; names at 0x59d0440), a flag being bit (1 << its enum value) in its category's word (names of
// the Menu flags at 0x59cf550). They live in a component of realm 0xbf0f9789's context
// (local_placements::realm_context), found through the getter at 0x59d0690 (byte +0x100: the
// component is up). Setting ORs into a pending set and clearing masks it out; either only acts when
// the request changes something, and the pending set is published three ticks later (0x95abe0,
// which also logs the Menu word as "UIStateFlag_Menu"). The UI's own widget logic raises and
// lowers them through a native action (0x9768b0: flags, bool on) and matches against them
// (0x9359f0: All/Any/Exact). Native readers: 0x6507b0 (Menu & 0x200090, Missions/CAS/Throwdowns),
// 0x5cfb00, 0x600e50, 0x7be600.
//
// The argument both entry points take is the flag struct by value (copied from the pointer): 18
// words, 72 bytes, in the struct's own order, which is not the category order. The Menu word is
// at +0x30: 0x85b650 zeroes a struct (0x597ff90), writes 0x20000 (Menu_Quickdrop, 17) there and
// sets it, and the publish at 0x95abe0 copies that word to the component's Menu field.
inline constexpr std::size_t flags_size = 72;
inline constexpr std::size_t menu_word = 0x30;
inline constexpr std::uint32_t menu_hub = 1u << 3; // UIStateFlag_Menu_HUB
inline constexpr std::uint32_t menu_cas = 1u << 7; // UIStateFlag_Menu_CAS

