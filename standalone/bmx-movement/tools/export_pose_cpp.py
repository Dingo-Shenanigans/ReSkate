"""Generate the observed PoseTrack dataset with measured resampling error bounds.

Only verified, uncensored native posture exports are accepted. A15Hz engine-time
grid uses position interpolation/quaternion SLERP from observed samples. Reported
errors compare against every original source key, not the unseen original clips.
"""
from __future__ import annotations
import argparse
import bisect
import importlib.util
import json
import math
from pathlib import Path
import re
import struct

spec=importlib.util.spec_from_file_location('bmx_export_pose_math',Path(__file__).with_name('pose_tracks.py'))
poses=importlib.util.module_from_spec(spec);spec.loader.exec_module(poses)
c=poses.comparison
ROOT=Path(__file__).resolve().parents[1]
MARKER='// Generated by tools/export_pose_cpp.py; observed data, not original clip source.'


def f32(value):return struct.unpack('<f',struct.pack('<f',value))[0]
def literal(value):
    text=format(f32(value),'.9g')
    if '.' not in text and 'e' not in text:text+='.0'
    return text+'f'
def array(values):return '{'+','.join(literal(value) for value in values)+'}'
def bone(position,rotation):
    flags=(1 if position is not None else 0)|(2 if rotation is not None else 0)
    return '{'+array(position or [0,0,0])+','+array(rotation or [0,0,0,1])+','+str(flags)+'}'
def maximum_error(values):
    return dict(samples=len(values),maximum=max(values) if values else None,
                rms=math.sqrt(sum(value*value for value in values)/len(values)) if values else None)
def sample(track,key,name,time,max_gap=.15):
    time=max(track['keys'][0]['t'],min(track['keys'][-1]['t'],time))
    # Generated key clocks are float32. Preserve a captured key when only its
    # representational rounding separates it from the original double clock.
    times=[entry['t'] for entry in track['keys']];i=bisect.bisect_left(times,time)
    for candidate in (i-1,i):
        if 0<=candidate<len(times) and abs(times[candidate]-time)<=1e-5:
            return track['keys'][candidate].get(key,{}).get(name)
    return poses.sample(track,key,name,time,max_gap)


def main(args):
    header=ROOT/'include/bmx/pose_track.hpp';text=header.read_text(encoding='utf-8')
    names=re.findall(r'"([A-Za-z]+)"',text.split('pose_bone_names{',1)[1].split('};',1)[0])
    if len(names)!=55 or len(set(names))!=55:raise ValueError('Expected55 explicit PoseBone names')
    tracks={};sources=[];excluded=[]
    for path in args.input:
        source=json.loads(path.read_text(encoding='utf-8-sig'))
        if (source.get('target')!='streets' or source.get('native_X_reflected_once') is not True
                or source.get('neutral_and_deltas_share_export_basis') is not True):
            raise ValueError('Expected native export with neutral and deltas reflected exactly once')
        sources.append(dict(path=str(path),sha256=c.sha(path.read_bytes()),rider_sha256=source['source_rider_sha256'],coverage_sha256=source['coverage_sha256']))
        for track in source['tracks']:
            pair=track['set'],track['slot']
            if (track.get('observation_window') or {}).get('partial') and not args.include_partial:
                excluded.append(dict(set=pair[0],slot=pair[1],source=str(path),reason='Explicitly partial source window excluded from production tracks'))
                continue
            if pair in tracks and args.prefer_first:continue
            if pair in tracks and not args.prefer_last:raise ValueError('Duplicate tuple; explicitly choose --prefer-last to replace older capture')
            if track['pose_reference'].get('skeleton_bound') is not True:raise ValueError('Unbound holder cannot supply posture tracks')
            tracks[pair]=dict(track,exporter_source_path=str(path))
    if not tracks:raise ValueError('No eligible observed tracks')
    if not 1<=args.hz<=60:raise ValueError('Resampling must be1..60Hz')
    cpp=[MARKER,'#include <bmx/pose_track.hpp>','namespace bmx { namespace {'];reports=[]
    for index,(pair,track) in enumerate(sorted(tracks.items())):
        first,last=track['keys'][0]['t'],track['keys'][-1]['t']
        phases=track.get('phase_observations') or []
        enter=next((phase['simulation_seconds']-track['fire_engine_seconds'] for phase in phases
            if phase.get('from_phase')==1 and phase.get('simulation_seconds') is not None),None)
        end=next((phase['simulation_seconds']-track['fire_engine_seconds'] for phase in phases
            if phase.get('from_phase')==5 and phase.get('to_phase')==0 and phase.get('simulation_seconds') is not None),None)
        exit_start=next((phase['simulation_seconds']-track['fire_engine_seconds'] for phase in phases
            if phase.get('to_phase')==5 and phase.get('simulation_seconds') is not None),None)
        hold=any(phase.get('to_phase') in (2,3,4) for phase in phases)
        if end is not None:last=min(last,end+.15)
        source_keys=[key for key in track['keys'] if first<=key['t']<=last]
        times=[first+i/args.hz for i in range(math.floor((last-first)*args.hz)+1)]+[last]
        # Keep observed native phase changes as explicit extra keys.
        for phase in phases:
            clock=c.finite(phase.get('simulation_seconds'))
            if clock is not None and first<=clock-track['fire_engine_seconds']<=last:times.append(clock-track['fire_engine_seconds'])
        times=sorted({f32(time) for time in times});resampled=[]
        neutral=track['neutral_local_pose']
        def resample_grid():
            result=[]
            for time in times:
                positions={};rotations={}
                for name in names:
                    channel='bone:'+name;p=sample(track,'delta_positions',channel,time);q=sample(track,'delta_rotations',channel,time)
                    if p is not None:positions[channel]=[f32(value) for value in p]
                    if q is not None:rotations[channel]=[f32(value) for value in q]
                result.append(dict(t=time,delta_positions=positions,delta_rotations=rotations))
            return result
        resampled=resample_grid();base_count=len(times)
        if args.maximum_position_error is not None or args.maximum_rotation_error_degrees is not None:
            for iteration in range(len(source_keys)+1):
                additions=set();sampled={'keys':resampled}
                for key in source_keys:
                    for name in names:
                        channel='bone:'+name;p=key['delta_positions'].get(channel);q=key['delta_rotations'].get(channel)
                        got_p=sample(sampled,'delta_positions',channel,key['t'],1);got_q=sample(sampled,'delta_rotations',channel,key['t'],1)
                        bad_p=(p is not None and args.maximum_position_error is not None and
                               (got_p is None or math.dist(p,got_p)>args.maximum_position_error))
                        bad_q=(q is not None and args.maximum_rotation_error_degrees is not None and
                               (got_q is None or poses.angle(q,poses.qnorm(got_q))>args.maximum_rotation_error_degrees))
                        if bad_p or bad_q:additions.add(f32(key['t']));break
                additions-=set(times)
                if not additions:break
                times=sorted(set(times)|additions);resampled=resample_grid()
        cpp.append(f'const PoseSample neutral_{index}{{{{')
        cpp.extend('    '+bone((neutral.get('bone:'+name) or {}).get('position'),(neutral.get('bone:'+name) or {}).get('rotation'))+',' for name in names)
        cpp.append('}};');cpp.append(f'const PoseKey keys_{index}[]{{')
        for key in resampled:
            time=key['t'];positions=key['delta_positions'];rotations=key['delta_rotations']
            cpp.append('    {'+literal(time)+',{{')
            cpp.extend('        '+bone(positions.get('bone:'+name),rotations.get('bone:'+name))+',' for name in names)
            cpp.append('    }}},')
        cpp.append('};')
        pe=[];qe=[];missing_p=missing_q=0;sampled={'keys':resampled}
        for key in source_keys:
            for name in names:
                channel='bone:'+name;n=neutral.get(channel) or {};p=key['delta_positions'].get(channel);q=key['delta_rotations'].get(channel)
                got_p=sample(sampled,'delta_positions',channel,key['t'],1)
                got_q=sample(sampled,'delta_rotations',channel,key['t'],1)
                if p is not None and n.get('position') is not None:
                    if got_p is None:missing_p+=1
                    else:pe.append(math.dist([n['position'][j]+p[j] for j in range(3)],[f32(n['position'][j])+got_p[j] for j in range(3)]))
                if q is not None and n.get('rotation') is not None:
                    if got_q is None:missing_q+=1
                    else:
                        actual=poses.qmul(q,n['rotation']);got=poses.qmul(poses.qnorm(got_q),poses.qnorm([f32(v) for v in n['rotation']]))
                        qe.append(poses.angle(actual,got))
        reports.append(dict(set=pair[0],slot=pair[1],module_id=pair[0]*10+pair[1],name=track['name'],generated_index=index,
            source_keys=len(track['keys']),retained_source_keys=len(source_keys),generated_keys=len(times),base_grid_keys=base_count,
            adaptive_extra_observed_keys=len(times)-base_count,mean_generated_keys_per_engine_second=(len(times)-1)/(last-first),engine_time_interval=[first,last],
            pose_reference=track['pose_reference'],enter_end_seconds=enter,exit_end_seconds=end,
            exit_start_seconds=exit_start,hold_available=hold,phase_observations=phases,
            observation_window=track.get('observation_window'),
            selected_source_path=track['exporter_source_path'],fire_observation=track['fire_observation'],
            available_neutral_position_bones=sum((neutral.get('bone:'+name) or {}).get('position') is not None for name in names),
            available_neutral_rotation_bones=sum((neutral.get('bone:'+name) or {}).get('rotation') is not None for name in names),
            observed_source_key_position_error_m=maximum_error(pe),observed_source_key_rotation_error_degrees=maximum_error(qe),
            source_position_keys_missing_after_resampling=missing_p,source_rotation_keys_missing_after_resampling=missing_q))
    cpp.append('const PoseTrack tracks[]{')
    for report in reports:
        index=report['generated_index'];enter=report['enter_end_seconds'];end=report['exit_end_seconds']
        exit_start=report['exit_start_seconds'];hold=report['hold_available']
        cpp.append(f"    {{static_cast<TrickId>({report['module_id']}),neutral_{index},std::span<const PoseKey>(keys_{index}),"+
                   literal(enter or 0)+','+literal(end or 0)+','+str(enter is not None).lower()+','+str(end is not None).lower()+','+
                   literal(exit_start or 0)+','+str(exit_start is not None).lower()+','+str(hold).lower()+'},')
    cpp.extend(['};','} // namespace','std::span<const PoseTrack> streets_observed_pose_tracks() noexcept { return tracks; }','} // namespace bmx',''])
    generated='\n'.join(cpp)
    if args.output.exists():
        if not args.replace_generated or not args.output.read_text(encoding='utf-8').startswith(MARKER):raise ValueError('Refuse replacing non-generated output')
    args.output.write_text(generated,encoding='utf-8')
    result=dict(schema=1,event='bmx_generated_observed_pose_tracks',generated_cpp=str(args.output),generated_sha256=c.sha(args.output.read_bytes()),
        exporter_sha256=c.sha(Path(__file__).read_bytes()),header_sha256=c.sha(header.read_bytes()),sources=sources,target_engine_hz=args.hz,
        partial_tracks_explicitly_allowed=args.include_partial,excluded_tracks=excluded,
        maximum_position_error_target_m=args.maximum_position_error,maximum_rotation_error_target_degrees=args.maximum_rotation_error_degrees,
        position_interpolation='linear',rotation_interpolation='shortest-arc quaternion SLERP',bone_enum_count=len(names),tracks=reports,
        limits=['Only verified native-fire exports are eligible. Partial windows are excluded unless --include-partial is explicit.',
                'An included partial track stops at its last observed key; it cannot establish a complete native trick trajectory.',
                'Every channel keeps separate position/rotation availability flags; missing bones are not filled.',
                'Native X reflection is already present in both neutral and deltas and is not applied again.',
                'Error maxima/RMS are measured against captured source key times, not mathematical bounds for unseen continuous motion.',
                'Captured pose includes the particular quick-hop/base-animation context, not a universal extracted clip.',
                'Actual holder-frame origin/binding must be mapped explicitly; Spring COM is not the observed skeleton reference.'])
    args.provenance.write_text(json.dumps(result,indent=2),encoding='utf-8')
    print(json.dumps(dict(output=str(args.output),tracks=len(reports),bytes=args.output.stat().st_size,
        maximum_observed_position_error_m=max(report['observed_source_key_position_error_m']['maximum'] or 0 for report in reports),
        maximum_observed_rotation_error_degrees=max(report['observed_source_key_rotation_error_degrees']['maximum'] or 0 for report in reports)),indent=2))


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--input',type=Path,action='append',required=True)
    parser.add_argument('--output',type=Path,required=True);parser.add_argument('--provenance',type=Path,required=True)
    parser.add_argument('--hz',type=float,default=15)
    preference=parser.add_mutually_exclusive_group();preference.add_argument('--prefer-last',action='store_true');preference.add_argument('--prefer-first',action='store_true')
    parser.add_argument('--include-partial',action='store_true',help='Explicit diagnostic-only partial track inclusion; provenance retains each censored observation window')
    parser.add_argument('--maximum-position-error',type=float);parser.add_argument('--maximum-rotation-error-degrees',type=float)
    parser.add_argument('--replace-generated',action='store_true');main(parser.parse_args())
