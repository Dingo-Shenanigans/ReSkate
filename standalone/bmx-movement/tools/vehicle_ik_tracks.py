def module(name,file):
    spec=importlib.util.spec_from_file_location(name,Path(__file__).with_name(file));result=importlib.util.module_from_spec(spec);spec.loader.exec_module(result);return result
poses=module('vehicle_pose_math','pose_tracks.py');c=poses.comparison
driver_tools=module('vehicle_fixed_requests','drive_target.py');pose_cpp=module('vehicle_cpp_literals','export_pose_cpp.py')
ROOT=Path(__file__).resolve().parents[1]
NODES=('Spring Body','Chassis Body','Front Wheel Front','Back Wheel Back','Headset','BB Body','Left Pedal Body','Right Pedal Body',
       '_animatedVehicleRootJoint','_rootBikeJoint','_BBAnimationTarget','_leftPedalAnimationTarget','_rightPedalAnimationTarget')
NODE_ENUM=('spring','chassis','front_wheel','rear_wheel','headset','bottom_bracket','left_pedal','right_pedal',
           'animated_vehicle_root','root_bike_joint','crank_target','left_pedal_target','right_pedal_target')
LIMBS={'LeftHand':'left_hand','RightHand':'right_hand','LeftFoot':'left_foot','RightFoot':'right_foot'}
MARKER='// Generated by tools/vehicle_ik_tracks.py; observed channels with explicit availability.'


def read_jsonl(path):
    with path.open(encoding='utf-8-sig') as source:
        for line in source:
            if line.strip():yield json.loads(line)


def windows(args,driver):
    requests=driver_tools.matrix_attempts(driver['scenario']);result=[]
    if args.poses:
        source=json.loads(args.poses.read_text(encoding='utf-8-sig'))
        if source['driver_sha256']!=c.sha(args.driver.read_bytes()):raise ValueError('Pose source/driver mismatch')
        tracks=source['tracks']
    elif args.coverage:
        source=json.loads(args.coverage.read_text(encoding='utf-8-sig'))
        if source['driver_sha256']!=c.sha(args.driver.read_bytes()):raise ValueError('Coverage/driver mismatch')
        tracks=[]
        for attempt in source['attempts']:
            if attempt['correct_fire_observed'] is not True:continue
            fire=next((fire for fire in attempt['fire_observations'] if (fire.get('set'),fire.get('slot'))==(attempt['set'],attempt['slot'])),None)
            if fire:tracks.append(dict(set=attempt['set'],slot=attempt['slot'],name=(attempt.get('current_runtime') or {}).get('name'),
                fire_observation=fire,fire_engine_seconds=fire['simulation_seconds'],phase_observations=attempt['native_animation_phase_transitions'],
                observation_window=dict(partial=not attempt['source_complete_through_attempt'])))
    else:raise ValueError('Explicit --poses or --coverage required')
    for track in tracks:
        # Post-idle rest can be censored even when the required observed
        # recovery tail is complete. Check the actual domain below instead.
        if ((track.get('observation_window') or {}).get('partial') and not any(
                phase.get('from_phase')==5 and phase.get('to_phase')==0 for phase in track['phase_observations'])):continue
        pair=track['set'],track['slot'];fire=track['fire_observation'];clock=track['fire_engine_seconds']
        request=next((request for request in requests if (request['set'],request['slot'])==pair and request['selection_start_seconds']-.1<=fire['t']<request['end_seconds']),None)
        if request is None:raise ValueError('No request corresponding to actual fire')
        idle=next((phase for phase in track['phase_observations'] if phase['from_phase']==5 and phase['to_phase']==0),None)
        if not idle:continue
        result.append(dict(id=pair[0]*10+pair[1],name=track['name'],fire=fire,origin=clock,
            end_engine=idle['simulation_seconds']+.15,start_wall=fire['t']-.15,end_wall=request['end_seconds'],
            neutral_start=(request['reset_release_seconds']+.3 if request.get('reset_release_seconds') is not None else request['start_seconds']),
            neutral_end=request['hop_request_seconds']-.05))
    return result


def local_transform(position,rotation,origin,frame_q):
    p=poses.rotate(poses.qinv(frame_q),[position[i]-origin[i] for i in range(3)]);q=poses.qmul(poses.qinv(frame_q),rotation)
    return dict(position=poses.reflect_p(p,True),rotation=poses.reflect_q(q,True))


def collect(args):
    driver=c.read_driver(args.driver,'streets');start=c.utc(driver['timeline_start_utc']);groups=windows(args,driver)
    frames=[];rejected=0
    path=args.directory/('body-physics.jsonl' if args.kind=='physical' else 'rider.jsonl')
    for source in read_jsonl(path):
        if source.get('sample_valid') is False or source.get('selection_current') is False:rejected+=1;continue
        wall=c.utc(source['utc'])-start;nodes={};ik={};identities={}
        if args.kind=='physical':
            bodies={body['role']:body for body in source['bodies'] if body.get('available')};chassis=bodies.get('Chassis Body')
            if chassis is None:rejected+=1;continue
            frame_q=poses.qnorm(chassis['rotation']);origin=chassis['world_center_of_mass']
            for name,body in bodies.items():
                transform=body.get('transform') or {};p=poses.vector(transform.get('position'));q=poses.qnorm(transform.get('rotation'))
                if name in NODES[:8] and p and q:
                    nodes[name]=local_transform(p,q,origin,frame_q);identities[name]=body['reference']['id']
        else:
            art=source.get('bike_articulation') or {}
            if art.get('selection_current') is False:rejected+=1;continue
            for name,value in (art.get('transforms') or {}).items():
                p=poses.vector(value.get('chassis_relative_position'));q=poses.qnorm(value.get('chassis_relative_rotation'))
                if value.get('available') is True and name in NODES[8:] and p and q:
                    nodes[name]=dict(position=poses.reflect_p(p,True),rotation=poses.reflect_q(q,True))
                    identities[name]=(value.get('transform') or {}).get('id')
            observations=source.get('limb_observations') or {};binding=observations.get('motion_binding') or {}
            if observations.get('available') is True and binding.get('available') is True and binding.get('matching_motion_count')==1:
                for limb in observations.get('limbs') or []:
                    state=limb.get('state') or {};name=LIMBS.get(str(state.get('_Type')))
                    if name is None or limb.get('available') is not True or limb.get('active') is not True:continue
                    current=limb.get('target') or {};target=current.get('state') or {}
                    # Literal current-target reference weight; no grip/pedal
                    # contact is inferred from this or from a selector number.
                    ik[name]=dict(position_weight=c.finite(state.get('PositionWeight')),
                        rotation_weight=c.finite(state.get('RotationWeight')),
                        reference_weight=c.finite(target.get('ReferenceLimbPositionWeight')),
                        target_selector=c.finite(state.get('_currentTargetID')),binding='unknown',
                        source_limb_id=(limb.get('reference') or {}).get('id'),
                        current_target_reference=current.get('reference'),goal_type=target.get('GoalType'),
                        target_active=target.get('Active'))
        frames.append(dict(wall=wall,simulation=source['simulation_seconds'],nodes=nodes,ik=ik,identities=identities))
    vehicles=[];limbs=[];excluded=[]
    for group in groups:
        before=[frame for frame in frames if group['neutral_start']<=frame['wall']<group['neutral_end']]
        selected=[frame for frame in frames if group['start_wall']<=frame['wall']<group['end_wall'] and frame['simulation']<=group['end_engine']]
        if not selected or max(frame['simulation'] for frame in selected)<group['end_engine']-.1:
            excluded.append(dict(id=group['id'],reason='No complete measured recovery tail'));continue
        for name in NODES:
            neutral=[frame['nodes'][name] for frame in before if name in frame['nodes']]
            keys=[dict(seconds=frame['simulation']-group['origin'],**frame['nodes'][name]) for frame in selected if name in frame['nodes']]
            ids={frame['identities'].get(name) for frame in before+selected if name in frame['nodes']}
            if len(neutral)<2 or len(keys)<3 or len(ids)!=1:continue
            n=dict(position=[statistics.median(value['position'][i] for value in neutral) for i in range(3)],rotation=poses.medoid([value['rotation'] for value in neutral]))
            vehicles.append(dict(id=group['id'],name=group['name'],node=name,neutral=n,keys=keys,
                source_transform_id=next(iter(ids)),animation_control_target=name in NODES[8:],fire_observation=group['fire']))
        for name in LIMBS.values():
            keys=[dict(seconds=frame['simulation']-group['origin'],command=frame['ik'][name]) for frame in selected if name in frame['ik']]
            ids={key['command']['source_limb_id'] for key in keys}
            if len(keys)>=3 and len(ids)==1:limbs.append(dict(id=group['id'],name=group['name'],limb=name,keys=keys,fire_observation=group['fire']))
    result=dict(schema=1,event='bmx_observed_vehicle_ik_tracks',source_kind=args.kind,source_path=str(path),source_sha256=c.sha(path.read_bytes()),
        source_driver_sha256=c.sha(args.driver.read_bytes()),source_window_sha256=c.sha((args.poses or args.coverage).read_bytes()),
        fixed_physics_available=args.kind=='physical',rejected_frames=rejected,vehicle_tracks=vehicles,ik_tracks=limbs,excluded=excluded,
        basis='Actual transform origins in actual Chassis worldCenterOfMass axes; one X reflection. IK values are coordinate-free literal controls.',
        limits=['Physical-part transform tracks do not prove a visible renderer binding.',
            'Animation control targets are independently tagged and are not simulated rigid body states.',
            'IK position/rotation/reference weights and current selector IDs are literal; contact binding remains unknown.',
            'Source windows require an actual correct native fire and observed Exit-to-Idle, with a measured recovery tail.',
            'Missing nodes, bones or controls are never reconstructed from another channel.'])
    with args.output.open('x') as target:json.dump(result,target,indent=2)
    print(json.dumps(dict(output=str(args.output),vehicle_tracks=len(vehicles),ik_tracks=len(limbs),excluded=excluded),indent=2))


def interp(keys,time,ik=False):
    times=[key['seconds'] for key in keys];time=max(times[0],min(times[-1],time));i=bisect.bisect_right(times,time)-1
    if i==len(keys)-1:return keys[i]
    a,b=keys[i],keys[i+1];t=(time-times[i])/(times[i+1]-times[i]);value=dict(seconds=time)
    if ik:
        value['command']=dict(a['command'])
        for field in ('position_weight','rotation_weight','reference_weight'):
            x,y=a['command'].get(field),b['command'].get(field);value['command'][field]=x+(y-x)*t if x is not None and y is not None else None
    else:
        value.update(position=[x+(y-x)*t for x,y in zip(a['position'],b['position'])],rotation=poses.slerp(a['rotation'],b['rotation'],t))
    return value


def generate(args):
    vehicles={};limbs={};sources=[]
    for path in args.input:
        source=json.loads(path.read_text())
        if source.get('event')!='bmx_observed_vehicle_ik_tracks':raise ValueError('Expected observed vehicle/IK source')
        sources.append(dict(path=str(path),sha256=c.sha(path.read_bytes()),source_sha256=source['source_sha256'],kind=source['source_kind']))
        for target,key,tracks in ((vehicles,'node',source['vehicle_tracks']),(limbs,'limb',source['ik_tracks'])):
            for track in tracks:
                identity=track['id'],track[key]
                if identity in target:
                    if args.prefer_first:continue
                    raise ValueError('Duplicate observed channel; --prefer-first required')
                target[identity]=dict(track,selected_source=str(path))
    f=pose_cpp.literal;array=pose_cpp.array;bone=pose_cpp.bone
    cpp=[MARKER,'#include <bmx/vehicle_pose.hpp>','namespace bmx { namespace {'];reports=[]
    for index,(pair,track) in enumerate(sorted(vehicles.items())):
        keys=track['keys'];first,last=keys[0]['seconds'],keys[-1]['seconds']
        times=sorted({pose_cpp.f32(time) for time in ({first,last}|{first+i/25 for i in range(math.floor((last-first)*25)+1)})})
        def narrow_grid():
            result=[]
            for time in times:
                value=interp(keys,time);value['seconds']=time
                value['position']=[pose_cpp.f32(component) for component in value['position']]
                value['rotation']=poses.qnorm([pose_cpp.f32(component) for component in value['rotation']]);result.append(value)
            return result
        for iteration in range(len(keys)+1):
            grid=narrow_grid();extra=set()
            for key in keys:
                got=interp(grid,key['seconds'])
                if math.dist(key['position'],got['position'])>.002 or poses.angle(key['rotation'],got['rotation'])>1:extra.add(pose_cpp.f32(key['seconds']))
            extra-=set(times)
            if not extra:break
            times=sorted(set(times)|extra)
        grid=narrow_grid();n=track['neutral'];node=NODE_ENUM[NODES.index(track['node'])]
        cpp.append(f'const VehiclePoseKey keys_{index}[]{{')
        cpp.extend('    {'+f(key['seconds'])+','+bone(key['position'],key['rotation'])+'},' for key in grid);cpp.append('};')
        pe=[];qe=[]
        for key in keys:
            got=interp(grid,key['seconds']);pe.append(math.dist(key['position'],got['position']));qe.append(poses.angle(key['rotation'],got['rotation']))
        reports.append(dict(id=track['id'],node=track['node'],node_enum=node,index=index,neutral=n,
            animation_control_target=track['animation_control_target'],source=track['selected_source'],source_transform_id=track['source_transform_id'],
            source_keys=len(keys),generated_keys=len(grid),maximum_observed_position_error_m=max(pe),maximum_observed_rotation_error_degrees=max(qe)))
    cpp.append('const VehiclePoseTrack tracks[]{')
    for report in reports:cpp.append('    {static_cast<TrickId>('+str(report['id'])+'),VehiclePoseNode::'+report['node_enum']+','+
        bone(report['neutral']['position'],report['neutral']['rotation'])+',std::span<const VehiclePoseKey>(keys_'+str(report['index'])+'),'+str(report['animation_control_target']).lower()+'},')
    cpp+=['};','} // namespace','std::span<const VehiclePoseTrack> streets_observed_vehicle_pose_tracks() noexcept { return tracks; }','} // namespace bmx','']
    ikcpp=[MARKER,'#include <bmx/ik_track.hpp>','namespace bmx { namespace {'];ikreports=[]
    for index,(pair,track) in enumerate(sorted(limbs.items())):
        # Retain original observed IK samples: selector IDs are discrete and
        # weight discontinuities must not be shifted onto a uniform time grid.
        ikcpp.append(f'const IKKey keys_{index}[]{{');available_counts={name:0 for name in ('position_weight','rotation_weight','reference_weight','target_selector')}
        for _,key in sorted({pose_cpp.f32(key['seconds']):key for key in track['keys']}.items()):
            value=key['command'];flags=0;weights=[]
            for bit,name in enumerate(('position_weight','rotation_weight','reference_weight')):
                number=c.finite(value.get(name));weights.append(number or 0)
                if number is not None:flags|=1<<bit;available_counts[name]+=1
            selector=c.finite(value.get('target_selector'))
            if selector is not None and abs(selector-round(selector))<1e-6:flags|=8;available_counts['target_selector']+=1
            else:selector=0
            ikcpp.append('    {'+f(key['seconds'])+',{'+','.join(f(weight) for weight in weights)+','+str(round(selector))+','+str(flags)+',IKContactBinding::unknown}},')
        ikcpp.append('};');ikreports.append(dict(id=track['id'],limb=track['limb'],index=index,source=track['selected_source'],keys=len(track['keys']),available_counts=available_counts,binding='unknown'))
    ikcpp.append('const IKTrack tracks[]{')
    for report in ikreports:ikcpp.append('    {static_cast<TrickId>('+str(report['id'])+'),RiderLimb::'+report['limb']+',std::span<const IKKey>(keys_'+str(report['index'])+')},')
    ikcpp+=['};','} // namespace','std::span<const IKTrack> streets_observed_ik_tracks() noexcept { return tracks; }','} // namespace bmx','']
    for path,lines in ((args.vehicle_cpp,cpp),(args.ik_cpp,ikcpp)):
        if path.exists() and (not args.replace_generated or not path.read_text().startswith(MARKER)):raise ValueError('Refuse replacing non-generated source')
        path.write_text('\n'.join(lines))
    result=dict(schema=1,event='bmx_generated_vehicle_ik_tracks',sources=sources,exporter_sha256=c.sha(Path(__file__).read_bytes()),
        vehicle_cpp_sha256=c.sha(args.vehicle_cpp.read_bytes()),ik_cpp_sha256=c.sha(args.ik_cpp.read_bytes()),
        vehicle_header_sha256=c.sha((ROOT/'include/bmx/vehicle_pose.hpp').read_bytes()),ik_header_sha256=c.sha((ROOT/'include/bmx/ik_track.hpp').read_bytes()),
        vehicle_tracks=reports,ik_tracks=ikreports,
        limits=['Physical-part tracks and animation-target tracks retain distinct source roles; renderer binding must be proved independently.',
            'Both position and quaternion are reflected once into the module Chassis COM frame; these are actual transform origins.',
            'Source-key resampling errors cover measured samples only, not unseen continuous trajectories.',
            'IK values preserve original sample times; selector IDs hold the preceding sample and never interpolate fractionally.',
            'IK contact binding remains unknown; no release or grip/pedal claim is inferred from weight alone.'])
    args.provenance.write_text(json.dumps(result,indent=2))
    print(json.dumps(dict(vehicle_tracks=len(reports),ik_tracks=len(ikreports),vehicle_ids=len({r['id'] for r in reports}),ik_ids=len({r['id'] for r in ikreports})),indent=2))


