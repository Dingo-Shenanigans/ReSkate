"""Generate command tables from measured native actuator tracks only."""
from __future__ import annotations
import argparse
import bisect
import importlib.util
import json
import math
from pathlib import Path

spec=importlib.util.spec_from_file_location('bmx_joint_export_math',Path(__file__).with_name('pose_tracks.py'))
poses=importlib.util.module_from_spec(spec);spec.loader.exec_module(poses);c=poses.comparison
ROOT=Path(__file__).resolve().parents[1]
MARKER='// Generated by tools/export_joint_cpp.py; observed actuator commands, never body trajectories.'
VECTOR_FIELDS=('target_position','rider_inertia','linear_spring','linear_damper','angular_spring','angular_damper')
QUAT_FIELDS=('target_rotation','rider_inertia_orientation')


def command(source):
    return dict(target_position=source['target_position'],target_rotation=source['target_rotation'],
        rider_inertia=source['rider_inertia'],rider_inertia_orientation=source['rider_inertia_orientation'],
        linear_spring=source['linear_spring'],linear_damper=source['linear_damper'],
        angular_spring=[source['slerp_spring']]*3,angular_damper=[source['slerp_damper']]*3,
        radial_limit=source['radial_limit'],acceleration_mask=sum(int(flag)<<i for i,flag in enumerate(
            source['linear_acceleration']+[source['slerp_acceleration']]*3)))


def sample(keys,time):
    time=max(keys[0]['seconds'],min(keys[-1]['seconds'],time));times=[key['seconds'] for key in keys]
    i=bisect.bisect_right(times,time)-1
    if i==len(keys)-1 or abs(times[i]-time)<1e-9:return keys[i]['command']
    a,b=keys[i]['command'],keys[i+1]['command'];t=(time-times[i])/(times[i+1]-times[i]);value={}
    for name in VECTOR_FIELDS:value[name]=[x+(y-x)*t for x,y in zip(a[name],b[name])]
    for name in QUAT_FIELDS:value[name]=poses.slerp(a[name],b[name],t)
    value['radial_limit']=a['radial_limit']+(b['radial_limit']-a['radial_limit'])*t
    value['acceleration_mask']=a['acceleration_mask'];return value


def differences(a,b):
    return dict(target_position_m=math.dist(a['target_position'],b['target_position']),
        target_rotation_degrees=poses.angle(poses.qnorm(a['target_rotation']),poses.qnorm(b['target_rotation'])),
        inertia_maximum_component=max(abs(x-y) for x,y in zip(a['rider_inertia'],b['rider_inertia'])),
        inertia_orientation_degrees=poses.angle(poses.qnorm(a['rider_inertia_orientation']),poses.qnorm(b['rider_inertia_orientation'])),
        gain_maximum_component=max(abs(x-y) for name in ('linear_spring','linear_damper','angular_spring','angular_damper') for x,y in zip(a[name],b[name])),
        radial_limit_m=abs(a['radial_limit']-b['radial_limit']),
        acceleration_mode_changed=a['acceleration_mask']!=b['acceleration_mask'])


def literal(value):
    value=float(value)
    if not math.isfinite(value):raise ValueError('Nonfinite generated command')
    text=format(value,'.17g');return text if '.' in text or 'e' in text else text+'.0'
def array(value):return '{'+','.join(literal(part) for part in value)+'}'
def cpp_command(value):
    return '{'+','.join(array(value[name]) for name in ('target_position','target_rotation','rider_inertia',
        'rider_inertia_orientation','linear_spring','linear_damper','angular_spring','angular_damper'))+','+literal(value['radial_limit'])+','+str(value['acceleration_mask'])+'}'


def main(args):
    sources=[];selected={};excluded=[]
    for path in args.input:
        source=json.loads(path.read_text(encoding='utf-8-sig'))
        if source.get('event')!='bmx_observed_joint_actuation_tracks' or source.get('target')!='streets':raise ValueError('Expected native observed command export')
        sources.append(dict(path=str(path),sha256=c.sha(path.read_bytes()),source_body_physics_sha256=source['source_body_physics_sha256'],
                            driver_sha256=source['driver_sha256'],
                            **{name:source[name] for name in ('independent_recovery_source','boundaries','limits') if name in source}))
        excluded.extend(source.get('excluded_tracks') or [])
        for track in source['tracks']:
            key=track['id'],track['phase']
            if key in selected:
                if args.prefer_first:continue
                raise ValueError('Duplicate command track; explicit --prefer-first required')
            selected[key]=dict(track,selected_source=str(path))
    generated=[]
    for pair,track in sorted(selected.items()):
        keys=[dict(seconds=key['seconds'],command=command(key['command'])) for key in track['keys']]
        item=dict(track,keys=keys,reference=command(track['reference']));generated.append(item)
        phases=track.get('phase_observations') or []
        held=any(phase.get('to_phase') in (2,3,4) for phase in phases)
        enter_end=next((phase['simulation_seconds']-track['origin_engine_seconds'] for phase in phases if phase.get('from_phase')==1),None)
        exit_start=next((phase['simulation_seconds']-track['origin_engine_seconds'] for phase in phases if phase.get('to_phase')==5),None)
        exit_end=next((phase['simulation_seconds']-track['origin_engine_seconds'] for phase in phases if phase.get('from_phase')==5 and phase.get('to_phase')==0),None)
        if track['id']<80 and held and enter_end is not None and exit_start is not None and exit_end is not None:
            for phase,start,end in [('enter',keys[0]['seconds'],enter_end),('recover',exit_start,min(keys[-1]['seconds'],exit_end+.15))]:
                times=sorted({start,end}|{key['seconds'] for key in keys if start<=key['seconds']<=end})
                offset=exit_start if phase=='recover' else 0
                generated.append(dict(track,phase=phase,reference=command(track['reference']),
                    origin_engine_seconds=track['origin_engine_seconds']+offset,
                    keys=[dict(seconds=time-offset,command=sample(keys,time)) for time in times]))
    if not generated:raise ValueError('No command tracks')
    thresholds=dict(target_position_m=.002,target_rotation_degrees=1.,inertia_maximum_component=.2,
                    inertia_orientation_degrees=1.,gain_maximum_component=1.,radial_limit_m=.005)
    lines=[MARKER,'#include <bmx/joint_actuation.hpp>','namespace bmx { namespace {'];reports=[]
    for index,track in enumerate(generated):
        original=track['keys'];first,last=original[0]['seconds'],original[-1]['seconds']
        if not first<last:raise ValueError('Degenerate observed command domain')
        times=sorted({first,last}|{first+i/args.hz for i in range(math.floor((last-first)*args.hz)+1)})
        for iteration in range(len(original)+1):
            grid=[dict(seconds=time,command=sample(original,time)) for time in times];extra=set()
            for key in original:
                error=differences(key['command'],sample(grid,key['seconds']))
                if error['acceleration_mode_changed'] or any(error[name]>bound for name,bound in thresholds.items()):extra.add(key['seconds'])
            extra-=set(times)
            if not extra:break
            times=sorted(set(times)|extra)
        grid=[dict(seconds=time,command=sample(original,time)) for time in times]
        errors=[differences(key['command'],sample(grid,key['seconds'])) for key in original]
        maxima={name:max(error[name] for error in errors) for name in thresholds}
        if any(maxima[name]>bound+1e-8 for name,bound in thresholds.items()):raise ValueError('Command resampling error target not met')
        lines.append(f'const JointActuationKey keys_{index}[]{{')
        lines.extend('    {'+literal(key['seconds'])+','+cpp_command(key['command'])+'},' for key in grid);lines.append('};')
        reports.append(dict(id=track['id'],name=track['name'],phase=track['phase'],index=index,reference=track['reference'],
            request_amplitude=track['request_amplitude'],origin_engine_seconds=track['origin_engine_seconds'],
            selected_source=track['selected_source'],source_identity=track['source_identity'],
            original_keys=len(original),generated_keys=len(grid),domain_seconds=[first,last],observed_source_key_error_maxima=maxima,
            **{name:track[name] for name in ('time_origin','phase_source') if name in track}))
    lines.append('const JointActuationTrack tracks[]{')
    for track in reports:
        lines.append('    {'+str(track['id'])+',JointActuationPhase::'+track['phase']+','+cpp_command(track['reference'])+','+
            literal(track['request_amplitude'])+',std::span<const JointActuationKey>(keys_'+str(track['index'])+')},')
    lines.extend(['};','} // namespace','std::span<const JointActuationTrack> streets_observed_joint_actuation_tracks() noexcept { return tracks; }','} // namespace bmx',''])
    if args.output.exists() and (not args.replace_generated or not args.output.read_text().startswith(MARKER)):
        raise ValueError('Refuse replacing non-generated command source')
    args.output.write_text('\n'.join(lines))
    provenance=dict(schema=1,event='bmx_generated_joint_actuation_tracks',generated_cpp=str(args.output),generated_sha256=c.sha(args.output.read_bytes()),
        exporter_sha256=c.sha(Path(__file__).read_bytes()),header_sha256=c.sha((ROOT/'include/bmx/joint_actuation.hpp').read_bytes()),
        sources=sources,excluded_source_tracks=excluded,base_engine_hz=args.hz,source_key_error_targets=thresholds,tracks=reports,
        limits=['Commands are observed joint targets, gains, limits and inertia; body positions/velocities are never replayed.',
            'Native inverse/reflection occurs once in source JSON; no coordinate transform is repeated in generated data.',
            'Adaptive command keys bound reconstruction errors only at actual captured source key times, not unseen continuous motion.',
            'Observed Hold/Loop paths have distinct enter and recover domains; runtime may freeze enter endpoint while held.',
            'Cycle paths retain measured timeline; longer or repeated loop behavior is not inferred.',
            'Bench first hop is fitting evidence; second hop remains held out.',
            'Pump-negative has no isolated neutral recovery in the source; positive transition is explicitly distinct.'])
    args.provenance.write_text(json.dumps(provenance,indent=2))
    print(json.dumps(dict(output=str(args.output),tracks=len(reports),unique_catalog_ids=len({r['id'] for r in reports if r['id']<80}),
                         bytes=args.output.stat().st_size,maximum_source_key_errors={name:max(r['observed_source_key_error_maxima'][name] for r in reports) for name in thresholds}),indent=2))


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--input',action='append',type=Path,required=True)
    parser.add_argument('--output',type=Path,required=True);parser.add_argument('--provenance',type=Path,required=True)
    parser.add_argument('--hz',type=float,default=25);parser.add_argument('--prefer-first',action='store_true');parser.add_argument('--replace-generated',action='store_true')
    args=parser.parse_args()
    if not math.isfinite(args.hz) or not 1<=args.hz<=100:raise ValueError('Command grid rate must be 1..100 Hz')
    main(args)
